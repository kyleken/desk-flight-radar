#!/usr/bin/env python3
"""Convert TTF fonts into anti-aliased VLW fonts embedded as C arrays.

Usage:  python3 tools/make_fonts.py        (run from the project folder)
Writes: src/fonts_data.h

VLW is the smooth-font format used by LovyanGFX / TFT_eSPI:
  header   6 x uint32 BE: glyph count, version, size, 0, ascent, descent
  metrics  7 x uint32 BE per glyph: unicode, height, width, xAdvance,
           dY (pixels above baseline), dX (left offset), 0
  bitmaps  8-bit alpha, width*height bytes per glyph
"""
import os
import struct
from PIL import ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FONT_DIR = os.path.join(ROOT, "fonts")
OUT = os.path.join(ROOT, "src", "fonts_data.h")

# name, ttf file, pixel size
FONTS = [
    ("ui8",    "Inter-Medium.ttf",        8),
    ("ui9",    "Inter-Medium.ttf",        9),
    ("ui11",   "Inter-SemiBold.ttf",     11),
    ("ui13",   "Inter-Bold.ttf",         13),
    ("ui17",   "Inter-Bold.ttf",         17),
    ("temp",   "Inter-SemiBold.ttf",     27),
    ("mono8",  "JetBrainsMono-Bold.ttf",  8),
    ("mono11", "JetBrainsMono-Bold.ttf", 11),
    ("mono15", "JetBrainsMono-Bold.ttf", 15),
]

EXTRA = "°·→−•±…×✓–—©"
# LovyanGFX binary-searches glyphs, so they must be sorted by code point.
CHARS = sorted(set([chr(c) for c in range(0x20, 0x7F)] + list(EXTRA)))


def build_vlw(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs = []
    for ch in CHARS:
        if ch != " " and font.getmask(ch).getbbox() is None:
            continue  # glyph not in this font
        adv = int(round(font.getlength(ch)))
        if ch == " ":
            glyphs.append((ord(ch), 0, 0, adv, 0, 0, b""))
            continue
        mask, offset = font.getmask2(ch, mode="L", anchor="ls")
        w, h = mask.size
        data = bytes(mask)
        dx, dy = offset[0], -offset[1]
        glyphs.append((ord(ch), h, w, adv, dy, dx, data))
    out = bytearray()
    out += struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent)
    for (u, h, w, adv, dy, dx, _) in glyphs:
        out += struct.pack(">7i", u, h, w, adv, dy, dx, 0)
    for g in glyphs:
        out += g[6]
    return bytes(out)


def main():
    lines = [
        "// Generated by tools/make_fonts.py - do not edit.",
        "// Fonts: Inter (SIL OFL 1.1, rsms/inter), JetBrains Mono (SIL OFL 1.1).",
        "#pragma once",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
    ]
    for name, ttf, size in FONTS:
        blob = build_vlw(os.path.join(FONT_DIR, ttf), size)
        lines.append(f"// {ttf} @ {size}px, {len(blob)} bytes")
        lines.append(f"static const uint8_t vlw_{name}[] = {{")
        for i in range(0, len(blob), 24):
            lines.append("  " + ",".join(str(b) for b in blob[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
